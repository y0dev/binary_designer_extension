/**
 * C-header emitter. Emits only — it never parses `.h`.
 *
 * Rules (see project prompt):
 *  - uintN -> uintN_t, intN -> intN_t, float32 -> float, float64 -> double
 *  - bytes/padding -> uint8_t x[N]; char[N] -> char x[N]
 *  - inline structs -> typedef struct <Parent>_<field>
 *  - reusable structs -> top-level typedefs in dependency order
 *  - enum fields -> typedef enum with UPPER_SNAKE constants, prefixed by the enclosing type
 *  - bits -> bitfield struct; widths must sum to <= container size
 *  - #pragma pack from design.packing; optional _Static_assert on sizeof
 */

import { Design, Field, LayoutResult } from './types';
import { toUpperSnake, sanitizeIdentifier } from './identifiers';
import { computeLayout, layoutFieldList } from './layout';
import { emitLayoutDoc } from './emitLayoutDoc';
import { parseType, scalarInfo } from './typeUtil';

export interface HeaderOptions {
  sourceFileName?: string;
  staticAssert?: boolean;
  includeStyle?: 'angle' | 'quote';
  /** declare enum fields with the generated enum typedef instead of their int type */
  enumTypedefForFields?: boolean;
  /** MAX capacity for array.countField members (0 / undefined -> FAM if last, else warn) */
  arrayMax?: number;
}

export interface HeaderResult {
  header: string;
  layoutDoc: string;
  warnings: string[];
}

export function generateHeader(design: Design, opts: HeaderOptions = {}): HeaderResult {
  const warnings: string[] = [];
  const packing = design.packing ?? 1;
  const guard = `${toUpperSnake(design.name)}_H`;
  const src = opts.sourceFileName ?? `${design.name}.design.json`;
  const include = opts.includeStyle === 'quote' ? '"stdint.h"' : '<stdint.h>';

  const out: string[] = [];
  out.push(`/* Generated by Binary File Designer — do not edit. Regenerate from ${src}. */`);
  out.push(`#ifndef ${guard}`);
  out.push(`#define ${guard}`);
  out.push('');
  out.push(`#include ${include}`);
  out.push('');
  if (packing !== false) {
    out.push(`#pragma pack(push, ${packing})          /* from design.packing */`);
    out.push('');
  } else {
    out.push('/* packing disabled — natural (compiler-default) alignment, no #pragma pack */');
    out.push('');
  }

  // ---- reusable structs, dependency order ----
  const order = topoSortStructs(design);
  for (const structName of order) {
    const def = design.structs![structName];
    const preludes: string[] = [];
    const body = emitStructBody(design, def.fields, structName, opts, warnings, preludes);
    for (const p of preludes) {
      out.push(p);
      out.push('');
    }
    out.push(`typedef struct ${structName} {`);
    out.push(...body);
    out.push(`} ${structName};`);
    out.push('');
  }

  // ---- top-level struct (+ its enum/bit/inline preludes) ----
  const topPreludes: string[] = [];
  const topBody = emitStructBody(design, design.fields ?? [], design.name, opts, warnings, topPreludes);
  for (const p of topPreludes) {
    out.push(p);
    out.push('');
  }
  out.push(`typedef struct ${design.name} {`);
  out.push(...topBody);
  out.push(`} ${design.name};`);
  out.push('');

  if (packing !== false) {
    out.push('#pragma pack(pop)');
    out.push('');
  }

  if (opts.staticAssert !== false) {
    const layout = computeLayout(design);
    out.push(
      `_Static_assert(sizeof(${design.name}) == ${layout.size}, "${design.name} layout drift");`,
    );
    out.push('');
  }

  out.push(`#endif /* ${guard} */`);
  out.push('');

  return {
    header: out.join('\n'),
    layoutDoc: emitLayoutDoc(design, { sourceFileName: src }),
    warnings,
  };
}

